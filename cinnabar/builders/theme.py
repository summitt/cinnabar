"""Compile a complete theme directory (~/.themes/<Name>) from tokens."""
import json
import shutil
from pathlib import Path

import jinja2

from .. import color as C
from ..recolor import Recolorer
from ..tokens import PROJECT_DIR, THEME_NAME
from . import metacity

BASES = {
    "dark": {"dir": "/usr/share/themes/Mint-Y-Dark", "bg": "#2e2e33", "fg": "#e1e1e1", "accent": "#35a854"},
    "light": {"dir": "/usr/share/themes/Mint-Y", "bg": "#f8f8f9", "fg": "#2b2b2b", "accent": "#35a854"},
}
COPY_DIRS = ["gtk-2.0", "gtk-3.0", "gtk-4.0", "libadwaita-1.5", "libadwaita-1.7", "cinnamon"]
TEXT_SUFFIXES = {".css", ".rc", ".svg", ".xml", ".theme", ""}
MARKER = ".cinnabar.json"


def _env():
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(str(PROJECT_DIR / "templates")),
                             autoescape=False, trim_blocks=True, lstrip_blocks=True)
    env.filters["alpha"] = C.alpha
    env.filters["mix"] = C.mix
    env.filters["lighten"] = C.lighten
    env.filters["darken"] = C.darken
    return env


def render_template(name, tokens):
    env = _env()
    return env.get_template(name).render(
        t=tokens.data, c=tokens.palette, w=tokens.data["window"], r={
            "control": tokens.get("controls.radius"), "large": tokens.get("controls.radius_large"),
            "popup": tokens.get("controls.popup_radius")},
        p=tokens.data["panel"], tokens=tokens)


def theme_dir(name=THEME_NAME):
    return Path.home() / ".themes" / name


def build(tokens, name=THEME_NAME, log=print):
    base = BASES["dark" if tokens.dark else "light"]
    src = Path(base["dir"])
    dst = theme_dir(name)
    if dst.exists():
        if not (dst / MARKER).exists() and any(dst.iterdir()):
            raise RuntimeError(f"{dst} exists and was not generated by Cinnabar; refusing to overwrite")
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    log(f"[theme] base {src.name} -> {dst}")

    rc = Recolorer({"bg": base["bg"], "fg": base["fg"], "accent": base["accent"]}, tokens.palette,
                   radii={"control": tokens.get("controls.radius"), "large": tokens.get("controls.radius_large")})

    for d in COPY_DIRS:
        if (src / d).is_dir():
            shutil.copytree(src / d, dst / d, ignore=shutil.ignore_patterns("thumbnail.png"))
    n_text = n_img = 0
    for p in dst.rglob("*"):
        if not p.is_file():
            continue
        if p.suffix in TEXT_SUFFIXES:
            try:
                txt = p.read_text()
            except UnicodeDecodeError:
                continue
            p.write_text(rc.map_text(txt))
            n_text += 1
        elif p.suffix == ".png":
            rc.map_image(p)
            n_img += 1
    log(f"[theme] recolored {n_text} text files and {n_img} images")

    # overrides
    g3 = render_template("gtk3-overrides.css.j2", tokens)
    for f in ("gtk.css", "gtk-dark.css"):
        fp = dst / "gtk-3.0" / f
        if fp.exists():
            fp.write_text(fp.read_text() + g3)
    g4 = render_template("gtk4-overrides.css.j2", tokens)
    for sub in ("gtk-4.0/gtk.css", "gtk-4.0/gtk-dark.css", "libadwaita-1.5/base.css", "libadwaita-1.7/base.css"):
        fp = dst / sub
        if fp.exists():
            fp.write_text(fp.read_text() + g4)
    cin = dst / "cinnamon" / "cinnamon.css"
    cin.write_text(cin.read_text() + render_template("cinnamon-overrides.css.j2", tokens))
    log("[theme] appended GTK3/GTK4/libadwaita/Cinnamon overrides")

    metacity.build(dst, tokens)
    log("[theme] generated window decorations (metacity-1)")

    (dst / "index.theme").write_text(
        "[Desktop Entry]\nType=X-GNOME-Metatheme\nName=%s\nComment=Generated by Cinnabar from preset %s\nEncoding=UTF-8\n\n"
        "[X-GNOME-Metatheme]\nGtkTheme=%s\nMetacityTheme=%s\nIconTheme=%s\nCursorTheme=%s\nButtonLayout=%s\n"
        % (name, tokens["name"], name, name, tokens.get("icons"), tokens.get("cursor.theme"),
           "close,minimize,maximize:" if tokens.get("window.buttons") == "left" else ":minimize,maximize,close"))
    (dst / "cinnamon" / "metadata.json").write_text(json.dumps({"name": name, "generated-by": "cinnabar"}))
    (dst / MARKER).write_text(json.dumps(tokens.data, indent=2))
    return dst
